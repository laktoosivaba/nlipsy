/**
 * Bundle the corpus for the tests, as one module.
 *
 * `conformance/cases/` lives above this package and is the acceptance gate for it, so
 * the runner reads the cases from a generated module rather than walking a directory: one
 * loader, one set of bytes, and a browser or a bundler that cannot see above the package
 * root still runs the same 125 cases.
 *
 * Generated and gitignored. Case files are carried as **text**, not as parsed values: one
 * case asserts `u64::MAX`, which `JSON.parse` rounds, so the parse has to happen in the
 * runner where `parseCase` can keep it (`test/corpus-runner.mjs`).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const workspace = path.resolve(pkg, '..');
const cases = path.join(workspace, 'conformance/cases');
const out = path.join(pkg, 'test/generated');

/** Every `*.json` under `root`, sorted, so that a failure list reads the same twice. */
function walk(root, prefix = '') {
  const found = [];
  for (const entry of fs
    .readdirSync(root, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const at = path.join(root, entry.name);
    const id = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) found.push(...walk(at, id));
    else if (entry.name.endsWith('.json')) found.push({ id, text: fs.readFileSync(at, 'utf8') });
  }
  return found;
}

if (!fs.existsSync(cases)) {
  throw new Error(`no corpus at ${cases}; this package is tested from inside the workspace`);
}
const found = walk(cases);
if (found.length === 0) {
  // The one failure mode a corpus run can have that looks like success: no cases found,
  // so no differences, so nothing to fail on.
  throw new Error(`the corpus at ${cases} holds no cases`);
}

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(
  path.join(out, 'corpus.mjs'),
  [
    '// Generated by `scripts/fixtures.mjs` from `conformance/cases/`. Do not edit.',
    `export const cases = ${JSON.stringify(found, null, 0)};`,
    '',
  ].join('\n'),
);

process.stdout.write(`bundled ${found.length} cases into test/generated/\n`);
